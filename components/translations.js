export function initTranslations() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        originalTexts[el.dataset.i18n] = el.textContent;
    });
}

export function applyTranslation(langCode) {
    document.documentElement.dir = 'ltr';

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (langCode === 'AR') {
            el.classList.add('ar-text');
        } else {
            el.classList.remove('ar-text');
        }
    });

    if (langCode === 'EN') {
        document.querySelectorAll('[data-i18n]').forEach((el) => {
            const key = el.dataset.i18n;
            if (originalTexts[key]) {
                el.textContent = originalTexts[key];
            }
        });

        document.documentElement.lang = 'en';
        return;
    }

    const dict = translations[langCode];
    if (!dict) return;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.dataset.i18n;

        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    document.documentElement.lang = langCode.toLowerCase();
}
